// lib/starter-context.mjs — generate references/futurebase-context.md.
//
// Inspects the futurebase checkout READ-ONLY and produces a Markdown summary an
// agent reads FIRST in a lead workspace (Method A in docs/project-lifecycle.md).
// Everything degrades gracefully: a missing file yields an omitted section, not
// a crash — the starter may be a partial checkout.

import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

function tryRead(path) {
	try {
		return readFileSync(path, 'utf8');
	} catch {
		return null;
	}
}

function tryJson(path) {
	const raw = tryRead(path);
	if (!raw) return null;
	try {
		return JSON.parse(raw);
	} catch {
		return null;
	}
}

function listDir(path, filter = () => true) {
	try {
		return readdirSync(path).filter(filter).sort();
	} catch {
		return [];
	}
}

function firstHeading(path) {
	const raw = tryRead(path);
	if (!raw) return null;
	const m = raw.match(/^#\s+(.+)$/m);
	return m ? m[1].trim() : null;
}

export function generateStarterContext(starterPath, { commit } = {}) {
	const pkg = tryJson(join(starterPath, 'package.json')) || {};
	const composer = tryJson(join(starterPath, 'composer.json')) || {};
	const wpEnv = tryJson(join(starterPath, '.wp-env.json')) || {};
	const nvmrc = (tryRead(join(starterPath, '.nvmrc')) || '').trim();
	const styleCss = tryRead(join(starterPath, 'style.css')) || '';
	const textDomain = (styleCss.match(/Text Domain:\s*(\S+)/) || [])[1] || pkg.name || 'unknown';

	const scripts = pkg.scripts || {};
	const interestingScripts = ['rename', 'block:new', 'cpt:new', 'build', 'verify', 'env:start', 'env:cli', 'a11y'].filter(
		(s) => scripts[s]
	);

	const docs = listDir(join(starterPath, 'docs'), (f) => f.endsWith('.md')).map((f) => {
		const h = firstHeading(join(starterPath, 'docs', f));
		return h ? `- \`docs/${f}\` — ${h}` : `- \`docs/${f}\``;
	});

	const skills = listDir(join(starterPath, '.claude', 'skills'), (f) => {
		try {
			return statSync(join(starterPath, '.claude', 'skills', f)).isDirectory();
		} catch {
			return false;
		}
	});

	const blocks = listDir(join(starterPath, 'src', 'blocks'), (f) => {
		try {
			return statSync(join(starterPath, 'src', 'blocks', f)).isDirectory();
		} catch {
			return false;
		}
	});

	const patternCount = listDir(join(starterPath, 'patterns'), (f) => f.endsWith('.php')).length;
	const hasThemeJson = existsSync(join(starterPath, 'theme.json'));

	const wpCore = wpEnv.core || 'unknown';
	const phpVersion = wpEnv.phpVersion || 'unknown';

	const lines = [];
	lines.push('# futurebase context');
	lines.push('');
	lines.push('> Generated by `futurebase lead init`. Read this **first** — it summarizes the');
	lines.push('> reusable starter this project would build on. Inspect the real starter');
	lines.push('> (read-only) only when you need to verify a capability.');
	lines.push('');
	lines.push('## Identity');
	lines.push('');
	lines.push(`- Theme slug / text domain: \`${textDomain}\``);
	if (composer.name) lines.push(`- Composer package: \`${composer.name}\``);
	lines.push(`- Starter path (read-only): \`${starterPath}\``);
	if (commit) lines.push(`- Starter commit at capture: \`${commit}\``);
	lines.push('');
	lines.push('## Stack & tooling');
	lines.push('');
	lines.push(`- WordPress: \`${wpCore}\`  ·  PHP: \`${phpVersion}\`  ·  Node: \`${nvmrc || 'unknown'}\``);
	lines.push('- Build: `@wordpress/scripts` (webpack) + `wp-env` for local WordPress.');
	lines.push('- Quality gate: `npm run verify` (theme contract + lint + phpcs + phpstan + pa11y-ci).');
	if (interestingScripts.length) {
		lines.push('');
		lines.push('Key npm scripts:');
		for (const s of interestingScripts) lines.push(`- \`npm run ${s}\` — \`${scripts[s]}\``);
	}
	lines.push('');
	lines.push('## Architecture conventions');
	lines.push('');
	lines.push(`- Block theme with ${hasThemeJson ? '`theme.json` as the configuration source of truth' : 'no theme.json found'}.`);
	lines.push('- Nine-item Technical Contract for the homepage/front-page workflow (tokens-first, pattern composition, fluid type) — enforced by `bin/verify-theme.sh`.');
	lines.push('- Projects are created from this repo as a GitHub template, then renamed with `npm run rename -- <slug>`.');
	lines.push(`- Theme-bound blocks: ${blocks.length ? '`' + blocks.join('`, `') + '`' : 'none scaffolded yet'} (scaffold with \`npm run block:new -- <slug>\`).`);
	lines.push(`- Patterns on disk: ${patternCount}.`);
	lines.push('- Code-registered CPTs scaffold with `npm run cpt:new -- <slug>`; ACF Pro UI is the alternative path.');
	lines.push('');
	if (docs.length) {
		lines.push('## Reference docs in the starter');
		lines.push('');
		lines.push(...docs);
		lines.push('');
	}
	if (skills.length) {
		lines.push('## Vendored WordPress skills available');
		lines.push('');
		lines.push(skills.map((s) => `\`${s}\``).join(', ') + '.');
		lines.push('');
	}
	lines.push('## Reuse notes for this project');
	lines.push('');
	lines.push('_Record here the specific starter capabilities relevant to this brief_');
	lines.push('_(patterns, blocks, ACF bindings, integrations). Keep client-specific_');
	lines.push('_analysis in this lead workspace — never modify the shared starter._');
	lines.push('');

	return lines.join('\n');
}
